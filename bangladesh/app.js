function createElement(tag, className, text) {
  const element = document.createElement(tag);
  if (className) element.className = className;
  if (text !== undefined) element.textContent = text;
  return element;
}

function createLink(text, href, className) {
  const link = createElement("a", className, text);
  link.href = href;
  link.target = "_blank";
  link.rel = "noopener noreferrer";
  return link;
}

function getFilteredDestinations() {
  const searchTerms = normalizeText(searchInput.value).split(" ").filter(Boolean);
  const division = divisionFilter.value;
  const category = categoryFilter.value;
  return DESTINATIONS.filter((destination) => {
    if (division && destination.division !== division) return false;
    if (category && !destination.categories.includes(category)) return false;
    if (!searchTerms.length) return true;
    const searchableText = normalizeText([
      destination.name,
      destination.division,
      destination.location,
      destination.summary,
      destination.description,
      destination.tags.join(" "),
      destination.aliases.join(" ")
    ].join(" "));
    return searchTerms.every((term) => searchableText.includes(term));
  });
}

function createCard(destination) {
  const card = createElement("article", "destination-card");
  const media = createElement("div", destination.image ? "card-media" : "card-media card-media-empty");
  if (destination.image) {
    const image = createElement("img");
    image.src = destination.image.src;
    image.alt = destination.image.alt;
    image.width = 900;
    image.height = 600;
    image.loading = "lazy";
    image.decoding = "async";
    media.append(image);
  } else {
    media.append(createElement("span", "card-media-mark", "✦"), createElement("span", "card-media-note", "Image not yet verified"));
  }
  media.append(createElement("span", "card-division", `${destination.division} Division`));

  const body = createElement("div", "card-body");
  const meta = createElement("p", "card-meta", `${destination.location} · ${CATEGORY_LABELS[destination.category]}`);
  const title = createElement("h3", "card-title", destination.name);
  const summary = createElement("p", "card-summary", destination.summary);
  const action = createElement("button", "card-action");
  action.type = "button";
  action.dataset.destinationId = destination.id;
  action.setAttribute("aria-label", `View details about ${destination.name}`);
  action.append(document.createTextNode("View details "), createElement("span", "", "↗"));
  body.append(meta, title, summary, action);
  card.append(media, body);
  return card;
}

function renderDestinations() {
  const filteredDestinations = getFilteredDestinations();
  destinationGrid.replaceChildren(...filteredDestinations.map(createCard));
  emptyState.hidden = filteredDestinations.length !== 0;
  destinationGrid.hidden = filteredDestinations.length === 0;
  if (!filteredDestinations.length) resultCount.textContent = "No heritage sites match your filters";
  else if (filteredDestinations.length === DESTINATIONS.length) resultCount.textContent = `Showing all ${DESTINATIONS.length} heritage sites`;
  else resultCount.textContent = `Showing ${filteredDestinations.length} of ${DESTINATIONS.length} heritage sites`;
}

function setPhotoCredit(container, image) {
  container.replaceChildren(
    createLink(`Photo by ${image.author} · ${image.sourceTitle}`, image.sourceUrl),
    document.createTextNode(" · "),
    createLink(image.license, image.licenseUrl),
    document.createTextNode(` · ${image.modifications}`)
  );
  if (image.imageNote) {
    const note = createElement("span", "credit-note", image.imageNote);
    container.append(" ", note);
  }
}

function openDetail(destinationId, trigger) {
  const destination = DESTINATION_BY_ID.get(destinationId);
  if (!destination) return;
  detailTrigger = trigger || null;
  detailDivision.textContent = `${destination.division} Division`;
  detailTitle.textContent = destination.name;
  detailSummary.textContent = destination.summary;
  detailDescription.textContent = destination.description;
  detailSeason.textContent = destination.season;
  detailAccess.textContent = destination.access;
  detailNotes.textContent = destination.notes;
  detailTags.replaceChildren(...destination.tags.map((tag) => createElement("span", "tag", tag)));
  if (destination.image) {
    detailImage.hidden = false;
    detailImage.src = destination.image.src;
    detailImage.alt = destination.image.alt;
    detailImage.width = destination.image.width;
    detailImage.height = destination.image.height;
    detailImageStatus.hidden = true;
    detailCaption.textContent = `${destination.name}, ${destination.location}`;
    setPhotoCredit(detailCredit, destination.image);
  } else {
    detailImage.hidden = true;
    detailImage.removeAttribute("src");
    detailImage.alt = "";
    detailImageStatus.hidden = false;
    detailCaption.textContent = "";
    detailCredit.textContent = "";
  }
  if (!detailDialog.open) detailDialog.showModal();
}

function renderCredits() {
  const illustratedDestinations = DESTINATIONS.filter((destination) => destination.image);
  const creditItems = illustratedDestinations.map((destination, index) => {
    const image = destination.image;
    const item = createElement("article", "credit-item");
    const number = createElement("p", "credit-number", String(index + 1).padStart(2, "0"));
    const title = createElement("h3", "", destination.name);
    const sourceLine = createElement("p", "credit-source");
    sourceLine.append(document.createTextNode("Source: "), createLink(image.sourceTitle, image.sourceUrl), document.createTextNode(" via Wikimedia Commons"));
    const licenseLine = createElement("p", "credit-license");
    licenseLine.append(document.createTextNode("License: "), createLink(image.license, image.licenseUrl), document.createTextNode(` · ${image.modifications}`));
    if (image.imageNote) licenseLine.append(" ", createElement("span", "credit-note", image.imageNote));
    item.append(number, title, sourceLine, licenseLine);
    return item;
  });
  if (!creditItems.length) creditItems.push(createElement("p", "credits-empty", "No exact images have been verified yet."));
  creditsContent.replaceChildren(...creditItems);
  creditsRendered = true;
}

function openCredits() {
  if (!creditsRendered) renderCredits();
  if (!creditsDialog.open) creditsDialog.showModal();
}

